-- PassHub schema for Supabase/PostgreSQL.
-- Run this in Supabase SQL Editor before connecting the browser app.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  role text not null default 'user'
    check (role in ('admin', 'manager', 'user')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tools (
  id bigint generated by default as identity primary key,
  name text not null,
  provider_name text,
  category text,
  description text,
  admin_url text,
  official_url text,
  status text not null default 'active'
    check (status in ('active', 'inactive', 'pending', 'suspended')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.license_plans (
  id bigint generated by default as identity primary key,
  tool_id bigint not null references public.tools(id) on delete restrict,
  plan_name text not null,
  total_quantity integer not null default 0 check (total_quantity >= 0),
  start_date date,
  end_date date,
  renewal_date date,
  auto_renew boolean not null default false,
  billing_type text not null default 'monthly'
    check (billing_type in ('monthly', 'yearly', 'one-time', 'custom')),
  price numeric(12, 2) not null default 0,
  status text not null default 'active'
    check (status in ('active', 'expired', 'pending', 'cancelled')),
  contract_number text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.members (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  member_number text not null unique,
  department text,
  status text not null default 'active'
    check (status in ('active', 'inactive', 'on_leave', 'suspended')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.license_assignments (
  id bigint generated by default as identity primary key,
  license_plan_id bigint not null references public.license_plans(id) on delete restrict,
  member_id bigint not null references public.members(id) on delete restrict,
  assigned_by uuid references public.profiles(id) on delete set null,
  assigned_at timestamptz not null default now(),
  released_by uuid references public.profiles(id) on delete set null,
  released_at timestamptz,
  status text not null default 'assigned'
    check (status in ('assigned', 'released', 'expired', 'cancelled')),
  release_reason text,
  notes text
);

create table if not exists public.operation_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  action_type text not null,
  target_type text not null,
  target_id bigint,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

